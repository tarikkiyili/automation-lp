import { test, expect } from '@playwright/test';

test('FAQ searches locally, normalizes Turkish, opens answers and clears safely', async ({ page }) => {
  await page.goto('/');
  const faq = page.locator('#faq');
  const input = faq.getByLabel('Sorular içinde ara');
  await expect(faq.locator('details')).toHaveCount(3);
  await input.focus();
  const requests = [];
  page.on('request', request => requests.push(request.url()));
  await input.fill('CALISAN');
  await expect(faq.locator('details').first()).toContainText(/çalışan/i);
  await expect(faq.locator('details[open]')).toHaveCount(0);
  await input.fill('google takvim');
  await expect(faq.locator('details')).toHaveCount(1);
  await expect(faq.locator('details[open]')).toHaveCount(0);
  await faq.locator('summary').click();
  await expect(faq.locator('.answer')).toBeVisible();
  await expect(faq.locator('.answer')).toContainText('iki yönlü');
  await input.fill('randevu iptali');
  await expect(faq.locator('summary').first()).toHaveText('Randevu iptal süresi belirleyebilir miyim?');
  await input.fill('zzzbulunamayansoru');
  await expect(faq.getByText('Bu aramada bir yanıt bulamadık.')).toBeVisible();
  await faq.getByRole('button', { name: 'Aramayı temizle' }).click();
  await expect(input).toBeFocused();
  await expect(faq.locator('details')).toHaveCount(3);
  await expect(faq.locator('details[open]')).toHaveCount(0);
  await input.fill('sms');
  await faq.getByRole('button', { name: 'Aramayı temizle' }).click();
  await page.waitForTimeout(350);
  await expect(faq.locator('details')).toHaveCount(3);
  expect(requests).toEqual([]);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});

test('FAQ debounces typing, offers more results and treats markup as text', async ({ page }) => {
  await page.goto('/');
  const faq = page.locator('#faq');
  const input = faq.getByLabel('Sorular içinde ara');
  await input.focus();
  await page.clock.install();
  await input.fill('randevu');
  await page.clock.fastForward(150);
  await expect(faq.locator('details')).toHaveCount(3);
  await input.fill('takvim');
  await page.clock.fastForward(150);
  await expect(faq.locator('details')).toHaveCount(3);
  await page.clock.fastForward(150);
  await expect(faq.locator('details').first()).toContainText('takvim');
  await input.fill('randevu');
  await page.clock.fastForward(300);
  await expect(faq.locator('details')).toHaveCount(8);
  await faq.getByRole('button', { name: 'Daha fazla yanıt göster' }).click();
  await expect(faq.locator('details')).toHaveCount(16);
  await input.fill('<img src=x onerror=alert(1)>');
  await page.clock.fastForward(300);
  await expect(faq.locator('.empty-results')).toBeVisible();
  await expect(faq.locator('img')).toHaveCount(0);
});

test('FAQ placeholder types, pauses on focus and respects reduced motion', async ({ page }) => {
  await page.goto('/');
  const input = page.locator('#faq-search-input');
  await input.scrollIntoViewIfNeeded();
  const original = 'Aklınızdaki soruyu yazın…';
  await expect.poll(() => input.getAttribute('placeholder'), {timeout: 6000}).not.toBe(original);
  await input.focus();
  await expect(input).toHaveAttribute('placeholder', original);
  await page.waitForTimeout(450);
  await expect(input).toHaveAttribute('placeholder', original);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await input.blur();
  await page.clock.install();
  await page.clock.fastForward(8000);
  await expect(input).toHaveAttribute('placeholder', original);
});

test('FAQ answers animate both ways and settle correctly after rapid toggles', async ({ page }) => {
  await page.goto('/');
  const details = page.locator('#faq details').first();
  const summary = details.locator('summary');
  await summary.scrollIntoViewIfNeeded();
  const closedHeight = (await details.boundingBox()).height;
  await summary.focus();
  await page.keyboard.press('Enter');
  await expect(details).toHaveAttribute('open', '');
  await expect.poll(() => details.evaluate(el => el.getAnimations().length)).toBe(0);
  expect((await details.boundingBox()).height).toBeGreaterThan(closedHeight + 20);
  await page.keyboard.press('Enter');
  await page.waitForTimeout(70);
  await page.keyboard.press('Enter');
  await expect.poll(() => details.evaluate(el => el.getAnimations().length)).toBe(0);
  await expect(details).toHaveAttribute('open', '');
  await page.keyboard.press('Enter');
  await expect(details).not.toHaveAttribute('open');
  expect((await details.boundingBox()).height).toBeCloseTo(closedHeight, 0);
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.keyboard.press('Enter');
  await expect(details).toHaveAttribute('open', '');
  expect(await details.evaluate(el => el.getAnimations().length)).toBe(0);
});

test('FAQ keeps one answer open and resets it when searching', async ({ page }) => {
  await page.goto('/');
  const faq = page.locator('#faq');
  const questions = faq.locator('summary');
  await questions.nth(0).click();
  await expect(faq.locator('details').nth(0)).toHaveAttribute('open', '');
  await questions.nth(1).click();
  await expect(faq.locator('details').nth(0)).not.toHaveAttribute('open');
  await expect(faq.locator('details[open]')).toHaveCount(1);
  await expect(faq.locator('details').nth(1)).toHaveAttribute('open', '');
  await faq.getByLabel('Sorular içinde ara').fill('randevu');
  await expect(faq.locator('details')).toHaveCount(8);
  await expect(faq.locator('details[open]')).toHaveCount(0);
  await questions.nth(0).click();
  await questions.nth(1).click();
  await expect(faq.locator('details[open]')).toHaveCount(1);
  await expect(faq.locator('details').nth(1)).toHaveAttribute('open', '');
  await expect(faq.getByRole('link', {name: 'Sorunuzu iletmek için tıklayın.'})).toHaveAttribute('href', '#request');
});
